/**
 * PRMPT — Prompt Quality Score.
 * Эвристическая оценка «съедобности» промпта для ИИ-агента: 0–100 + подсказки.
 */
import { normalizeConfig } from './schema.js';
import { ENGINE_IDS } from './catalog.js';

const has = (s) => typeof s === 'string' && s.trim().length > 0;
const len = (s) => (typeof s === 'string' ? s.trim().length : 0);

function check(id, label, weight, status, advice, why) {
  return { id, label, weight, status, advice, why };
}

export function scorePrompt(rawCfg) {
  const cfg = normalizeConfig(rawCfg);
  const p = cfg.prompt;
  const g = cfg.gameplay;
  const checks = [];

  /* 1. Роль */
  const roleOk = has(p.role) && len(p.role) > 8;
  checks.push(check('role', 'Задана роль агента', 10, roleOk ? 'pass' : 'fail',
    roleOk ? `Роль: ${p.role}` : 'Укажите конкретную роль, например «Senior Godot 4 Gameplay Engineer».',
    'Модель без роли отвечает «вообще»: смешивает уровни абстракции и стиль кода.'));

  /* 2. Стек */
  const stackOk = ENGINE_IDS.includes(cfg.meta.engine) && has(cfg.meta.engine);
  checks.push(check('stack', 'Зафиксирован стек и версия движка', 10, stackOk ? 'pass' : 'fail',
    stackOk ? `Стек зафиксирован: ${cfg.meta.engine}, запрет на смену прописан в ограничениях.` : 'Выберите движок — иначе агент начнёт «угадывать» библиотеки.',
    'Незафиксированный стек — причина №1 для случайных зависимостей и несовместимых API.'));

  /* 3. DoD */
  const dod = p.dod?.length ?? 0;
  checks.push(check('dod', 'Есть критерии приёмки (DoD)', 12, dod >= 3 ? 'pass' : dod > 0 ? 'warn' : 'fail',
    dod >= 3 ? `${dod} критерия приёмки` : dod > 0 ? `Только ${dod} критерий — мало для самопроверки агента.` : 'Нет критериев приёмки: агент сам решит, что «готово».',
    'DoD превращает «вроде работает» в проверяемый чеклист. Без него агент закрывает задачу на середине.'));

  /* 4. Запреты */
  const forb = p.forbidden?.length ?? 0;
  const antiHall = (p.forbidden ?? []).some((x) => /выдум|галлюцин|несуществующ/i.test(x));
  checks.push(check('forbidden', 'Прописаны запреты', 10, forb >= 3 ? 'pass' : forb > 0 ? 'warn' : 'fail',
    forb >= 3 ? `${forb} запретов` : 'Мало запретов. Добавьте хотя бы: не рефакторить вне задачи, не добавлять зависимости, не оставлять заглушки.',
    'Запреты дешевле починки последствий: агент по умолчанию стремится «улучшить» весь проект.'));

  /* 5. Анти-галлюцинации */
  checks.push(check('anti-hallucination', 'Запрет на выдуманные API', 8, antiHall ? 'pass' : 'fail',
    antiHall ? 'Прописан запрет изобретать несуществующие API.' : 'Добавьте: «не выдумывать несуществующие API движка — сообщить, если метода нет».',
    'LLM уверенно выдумывает методы движков. Явный запрет + требование сообщить снижает это в разы.'));

  /* 6. Атомарность */
  const atomic = has(p.iterationSize);
  checks.push(check('atomicity', 'Ограничен размер итерации', 8, atomic ? 'pass' : 'fail',
    atomic ? p.iterationSize : 'Задайте правило: одна атомарная фича за итерацию.',
    'Широкие задачи («сделай игру») агент выполняет поверхностно: везде по чуть-чуть, ничего не работает целиком.'));

  /* 7. Объём / Scope Guard */
  const scopeOk = has(g.winCondition) && has(g.loseCondition) && (g.coreLoop?.length ?? 0) >= 3;
  checks.push(check('scope', 'Очерчен объём и правила игры', 10, scopeOk ? 'pass' : 'warn',
    scopeOk ? 'Кор-цикл, условия победы и поражения заданы.' : 'Опишите кор-цикл (3+ шага), победу и поражение — это рамка, за которую агенту нельзя выходить.',
    'Без явного «что НЕ входит» агент достраивает фичи сам: аккаунты, мультиплеер, аналитику.'));

  /* 8. Архитектура */
  const patOk = (cfg.tech.patterns?.length ?? 0) >= 2;
  checks.push(check('architecture', 'Выбраны архитектурные паттерны', 8, patOk ? 'pass' : 'warn',
    patOk ? `${cfg.tech.patterns.length} паттерна задано` : 'Выберите 2–4 паттерна: FSM, шина событий, пул объектов.',
    'Без паттернов агент лепит логику в одном файле — через итерацию это уже не рефакторится дёшево.'));

  /* 9. Данные/баланс */
  const dataOk = cfg.tech.dataDriven === true;
  checks.push(check('data-driven', 'Баланс вынесен в конфиг', 6, dataOk ? 'pass' : 'warn',
    dataOk ? 'Числа баланса — в конфиг-файле.' : 'Включите «данные отдельно от логики»: числа в конфиг.',
    'Магические числа в коде — то, что агент правит наугад, ломая уже отлаженное поведение.'));

  /* 10. Политика вопросов */
  checks.push(check('questions', 'Определена политика вопросов', 6, p.askQuestions ? 'pass' : 'warn',
    p.askQuestions ? 'Агенту разрешено задавать один уточняющий вопрос при неоднозначности.' : 'Без политики агент либо молча угадывает, либо засыпает вопросами.',
    'Один вопрос вместо десяти: «спрашивай при взаимоисключающих прочтениях, иначе решай сам и помечай решение».'));

  /* 11. Кор-механика конкретна */
  const mech = len(cfg.meta.coreMechanic);
  checks.push(check('mechanic', 'Кор-механика описана конкретно', 8, mech >= 80 ? 'pass' : mech >= 30 ? 'warn' : 'fail',
    mech >= 80 ? `${mech} символов — достаточно для однозначного прочтения.` : 'Опишите механику через действия и правила: что нажимает игрок и что происходит.',
    'Расплывчатая механика → агент реализует своё видение и вы потеряете итерацию на переделку.'));

  /* 12. План итераций */
  const roadmapOk = p.includeRoadmap === true && (cfg.meta.targetIterations ?? 0) >= 3;
  checks.push(check('roadmap', 'Есть план из нескольких итераций', 4, roadmapOk ? 'pass' : 'warn',
    roadmapOk ? `План на ${cfg.meta.targetIterations} итераций сгенерирован.` : 'Спланируйте 4+ итерации — это декомпозиция задачи на проверяемые шаги.',
    'Декомпозиция — единственный способ держать агента в рамках: каждая итерация обязана заканчиваться работающим проектом.'));

  const total = checks.reduce((s, c) => s + c.weight, 0);
  const earned = checks.reduce((s, c) => s + (c.status === 'pass' ? c.weight : c.status === 'warn' ? c.weight * 0.5 : 0), 0);
  const score = Math.round((earned / total) * 100);

  const grade = score >= 90 ? { label: 'Отличный промпт', tone: 'excellent' }
    : score >= 75 ? { label: 'Хороший промпт', tone: 'good' }
    : score >= 55 ? { label: 'Рабочий, но рискованный', tone: 'fair' }
    : { label: 'Агент уйдёт в сторону', tone: 'poor' };

  return {
    score,
    grade,
    checks,
    passed: checks.filter((c) => c.status === 'pass').length,
    total: checks.length,
    tips: decompositionTips()
  };
}

